import { useEffect, useState } from "react";
import { LfcAgreement } from "@/components/charts/lfc-agreement";
import { Panel, Section, Skeleton } from "@/components/ui/card";
import { Table, Td, Th } from "@/components/ui/table";
import { fmtNum } from "@/lib/format";
import { useTheme } from "@/lib/theme";
import { comparisonsFor } from "@/lib/validation";
import type { ValidationResults } from "@/lib/validation-results";

/** The hard-coded validation data is a few hundred kilobytes, so it is loaded only when
 * this section renders (Vite splits the module into its own chunk). */
function useValidationResults(): ValidationResults | null {
  const [data, setData] = useState<ValidationResults | null>(null);
  useEffect(() => {
    let live = true;
    import("@/lib/validation-results").then((m) => {
      if (live) setData(m.VALIDATION_RESULTS);
    });
    return () => {
      live = false;
    };
  }, []);
  return data;
}

/** The analysis pipeline rerun on GEO series whose authors published genome-wide differential
 * expression, with the pipeline's log2 fold change against the authors' for every comparison. */
export function PipelineValidation() {
  const data = useValidationResults();
  const { resolved } = useTheme();
  return (
    <Section
      id="pipeline-validation"
      title="Does the pipeline reproduce published results?"
      info="Separate from the discovery evals above: this checks the analysis step. Designs were written by hand from the GEO metadata; the pipeline then ran from NCBI's counts with default parameters."
    >
      <div className="max-w-[75ch] text-[15px] text-ink-2">
        <p>
          Three GEO series whose authors published full differential expression tables were run
          through the standard pipeline from the same NCBI raw counts the app uses. Every chart
          plots the pipeline's log2 fold change against the authors' value for the genes tested on
          both sides; points on the dashed line agree exactly. R² is the squared Pearson correlation
          of the two fold changes over all shared genes.
        </p>
        <p className="mt-2 text-[13px] text-ink-3">
          Published tables come from GEO supplementary files, bioRxiv and Europe PMC. Genes are
          matched on NCBI GeneID. Regenerated by{" "}
          <span className="accession">mise run validate:published</span>; the write-up is in{" "}
          <span className="accession">docs/validation</span>.
        </p>
      </div>

      {!data ? (
        <div className="mt-6 grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {["a", "b", "c"].map((k) => (
            <Skeleton key={k} className="h-[380px]" />
          ))}
        </div>
      ) : (
        <>
          {data.datasets.map((ds) => {
            const comparisons = comparisonsFor(data, ds);
            return (
              <div key={ds.gse} className="mt-8">
                <div className="mb-3 max-w-[90ch]">
                  <h3 className="flex flex-wrap items-baseline gap-x-2">
                    <span className="accession text-[13px] text-ink-2">{ds.gse}</span>
                    <span>{ds.title}</span>
                  </h3>
                  <p className="mt-1 text-[13px] text-ink-2">
                    {ds.paper} (PMID <span className="accession">{ds.pmid}</span>) · {ds.design}
                  </p>
                  <p className="mt-0.5 text-[13px] text-ink-3">Published: {ds.published}.</p>
                </div>
                <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
                  {comparisons.map((c) => (
                    <Panel key={c.contrast}>
                      <div className="mb-2 flex flex-wrap items-baseline justify-between gap-x-3">
                        <span className="text-[13px] font-medium text-ink">{c.title}</span>
                        <span className="num text-[12px] text-ink-3">
                          {c.n} · <span className="accession">{c.design}</span>
                        </span>
                      </div>
                      <LfcAgreement comparison={c} themeKey={resolved} />
                    </Panel>
                  ))}
                </div>
              </div>
            );
          })}

          <Panel className="mt-8 overflow-x-auto">
            <Table>
              <thead>
                <tr>
                  <Th>Comparison</Th>
                  <Th className="text-right">Samples</Th>
                  <Th className="text-right">Shared genes</Th>
                  <Th className="text-right">R²</Th>
                  <Th className="text-right">Spearman</Th>
                </tr>
              </thead>
              <tbody>
                {data.comparisons.map((c) => (
                  <tr key={`${c.gse}-${c.contrast}`}>
                    <Td className="py-2">
                      <span className="accession text-ink-2">{c.gse}</span> {c.title}
                    </Td>
                    <Td className="num py-2 text-right">{c.n}</Td>
                    <Td className="num py-2 text-right">{c.shared.toLocaleString()}</Td>
                    <Td className="num py-2 text-right font-medium">{fmtNum(c.r2, 2)}</Td>
                    <Td className="num py-2 text-right">{fmtNum(c.spearman, 2)}</Td>
                  </tr>
                ))}
              </tbody>
            </Table>
            <p className="mt-3 max-w-[90ch] text-[13px] text-ink-3">
              Both statistics compare the pipeline's unshrunk log2 fold change with the authors'
              value, gene by gene, over every gene tested on both sides. The authors' methods differ
              from the pipeline's (Cuffdiff for GSE52778, a paired t-test on voom values for
              GSE144269), so the comparison is of effect sizes, not of significance calls.
            </p>
          </Panel>
        </>
      )}
    </Section>
  );
}
